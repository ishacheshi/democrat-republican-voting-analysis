"""## Methods

We will refer to the difficulty of voting experienced by Democrats as the random variable $X$, while the difficulty of voting experienced by Republicans is described by a random variable $Y$. The Wilcoxon Rank Sum Test Hypothesis of Comparisons is the most appropriate test for our data set. First, the test is intended for unpaired data, like ours. Second, the test can be used for non-parametric data, meaning it makes no assumptions about the shape of the underlying distribution of data—which is good, as we don't have enough information to assume normality across our Likert scale. Furthermore, the Hypothesis of Comparisons version allows for ordinal variables, meaning our Likert scale data can be used.

To use the Wilcoxon Rank Sum Test Hypothesis of Comparisons, we must make two assumptions. First, that our data is ordinal, which as a Likert variable, it is. Second, that our data is IID. While YouGov's respondents are not strictly independent, as users can recommend the site to other users, YouGov's user base is in the millions and surveys are often sent out randomly to users who meet certain given criteria (e.g. being a US citizen.) Therefore, a lack of independence is unlikely. Regarding whether our data is identically distributed, when we look at the histogram below of difficulty values separated by party, we see that lower indications of difficulty tend to be higher, and vica versa. We notice no distinct substructure. Given our large sample size of 1,136, one would expect that is there was any distinct clusterings of subgroups with differing underlying distributions, they would be clear in this plot. Therefore, we have no evidence suggesting that our data is not identically distributed—for our X and Y random variables separately. Therefore, we will assume IID.
