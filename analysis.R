In order to determine which respondents fall into the category of Democratic voters vs. Republican voters, we  turn to established methods of determining voter affiliation. Petrocik (2009) examined the tendency of many American voters to identify as independent, while having a clearly partisan voting history. For this reason, we take into account not just the respondent's self-identification but their reported previous voting history. To determine a respondent's true party leaning, we first count how many times a respondent voted for a Democratic candidate, tallying up their Democrat 'points.' Finally, we add an additional point if the individual's self-identified as such, creating the Democratic point total. We then do the same for their Republican 'points.' We then compare the two point totals, and classify the respondent into a party depending on the higher total. An individual with equal points will be labeled an independent, and not used in our analysis. Of our respondents, 32 were classified as independent using this method, leaving a final 1136 respondents who lean either Democrat or Republican and responded to the survey's difficulty question.

