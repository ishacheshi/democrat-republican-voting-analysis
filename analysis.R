"""We start with a null hypothesis that Democrats and Republicans experience similar levels of difficulty voting, or, more explicitly, that the probability that a draw from $X$ ranks higher than a draw from $Y$ is the same as the probability that a draw from $X$ ranks higher than a draw from $Y$ ($P(X>Y) = P(Y>X)$). For this we will pursue a two-sided test. We decide on a threshold p-value of $0.05$, as is industry standard, below which we will reject our $H_0$ in favor of our alternate hypothesis, that Democrats and Republicans experience different levels of difficulty voting $P(X>Y) \neq P(Y>X)$."""

head(df_coded)

democrats <- filter(df_coded_votehard_filt, party=="Democrat")
republicans <- filter(df_coded_votehard_filt, party=="Republican")

"""## Results"""

result = wilcox.test(democrats$votehard, republicans$votehard, paired = FALSE)
print(result)

"""We find that the two-sided Wilcoxon Rank Sum Test supports rejecting our null hypothesis (p = `r result$p.value` < 0.05) in favor of our alternative hypothesis that $P(X>Y) \neq P(Y>X)$. This value is definitely statistically significant, as it is multiple orders of magnitude below our threshold value of $0.05$.

<!-- fill in: code in values -->
"""

# more parameters two-sided test
result = wilcox.test(democrats$votehard, republicans$votehard, mu=0, alt="two.sided", conf.int = T, paired = FALSE)
print(result)

# try a one-sided test to see what the difference is
# alternative hypothesis is that democrats have greater difficulty
one_sided_result_1 = wilcox.test(democrats$votehard, republicans$votehard, alt="greater", conf.int = T, paired = FALSE)
print(one_sided_result_1)

# alternative hypothesis is that democats have less difficulty
one_sided_result_2 = wilcox.test(democrats$votehard, republicans$votehard, alt="less", conf.int = T, paired = FALSE)
print(one_sided_result_2)

D_hard <- sum(democrats$votehard >= 3)
R_hard <- sum(republicans$votehard >= 3)

percen_D_hard <- round(100*D_hard/nrow(df_coded_votehard_filt), 2)
percen_R_hard <- round(100*R_hard/nrow(df_coded_votehard_filt), 2)
diff_percen_hard <- percen_D_hard - percen_R_hard
scale_US = round(345997551*diff_percen_hard/100)

"""In order to investigate which group experiences more difficulty voting, we conduct two one-sided Wilcoxon Rank Sum Tests in order to see which alternative hypothesis, $P(X>Y) > P(Y>X)$ or $P(X>Y) < P(Y>X)$, is more likely given our data. We find $P(X>Y) < P(Y>X)$ to be more likely (`r one_sided_result_2$p.value` > `r one_sided_result_1$p.value`).

