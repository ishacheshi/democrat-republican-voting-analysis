df_coded <- anes_2022_data_initial_subset

# create function that codes for D=democrat or R=republican based on house/senate/gov voting history
recode_party_vote_hist <- function(x) {
  x <- ifelse(x == 1, "D", x)
  x <- ifelse(x == 2, "R", x)
  return(x)
}

# create function that codes for D=democrat or R=republican based on presidential election choice and leaning
recode_party_vote_pres <- function(x) {
  x <- ifelse(x == 1, "R", x)
  x <- ifelse(x == 2, "D", x)
  return(x)
}

# identify Democrats and Republican options based on voting history
df_coded[, c("house22p", "senate22p", "gov22p", "pid1d", "pid1r")] <- lapply(df_coded[, c("house22p", "senate22p", "gov22p", "pid1d", "pid1r")], recode_party_vote_hist)

# identify Democrats and Republicans based on pres election and leaning
df_coded[, c("vote20", "vote24dt", "pidlean")] <- lapply(df_coded[, c("vote20", "vote24dt", "pidlean")], recode_party_vote_pres)

# function to calculate D and R scores
count_values <- function(row, values_to_count) {
 sum(row %in% values_to_count)
}

df_coded$D_count <- apply(df_coded, 1, count_values, "D")

df_coded$R_count <- apply(df_coded, 1, count_values, "R")

# if D_count > R_count = Democrat, if D_count < R_count = Republican, else = other
df_coded <- df_coded %>%
  mutate(party = case_when(
    D_count > R_count ~ "Democrat",
    D_count < R_count ~ "Republican",
    D_count == R_count ~ "Other"
  ))

