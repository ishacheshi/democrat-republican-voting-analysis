Some may argue that the practical significance of this effect will depend on how much the expectation values of the two groups truly differ—that a very small difference in means is unlikely to have practical significance. We can assess the practical significance of this effect by estimating the amount of Democrats that experience significant difficulty voting in comparison to the amount of Republicans. We define significant difficulty voting as a Likert value of >3. The number of Democrats with a difficulty rating >3 is `r D_hard`, or `r percen_D_hard`% of our total sample. The number of Republicans with a difficulty rating >3 is `r R_hard`, or `r percen_R_hard`% of our total sample. The discrepancy between these two percentages is `r diff_percen_hard`%, which could represent `r scale_US` voters if we scale to the US population.

As previously discussed, even 150,000 swing state voters can alter the results of the US national elections. Therefore, our results are definitely practically significant. There remain some limitations to our result—for instance, this survey was not collected on a representative sample, making our conclusions not actually generalizable to the national population. However, these results are still a good initial step in this analysis, and will provide insight to inform the design of more representative studies in the future.

