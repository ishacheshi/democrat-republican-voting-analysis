## Introduction

The right to vote is a cornerstone of American democracy—yet, in recent years, many have questioned whether this right is truly being protected by our current policies. From attempts to purge voter rolls (Cole, 2024), to laws in Georgia criminalizing the handing out of food and water to voters waiting in line (ACLU, 2021), high-profile cases of voter suppression have rocketed the topic to the forefront of our national debate. Partisan groups often claim that voter suppression tactics are politically motivated, and affect one party more than the other. Given the extreme closeness of US national elections—some estimates put the number of swing state votes truly deciding US presidential elections as low as 150,000 (Hernandez, 2024)—even small differences in voter suppression across party lines could have far-reaching consequences for our elections. To begin to address this issue, of interest to politicians and voting rights groups alike,
we ask the following question:

*Do Democratic voters or Republican voters experience more difficulty voting?*

The answer to this question will have material significance to voter's rights activists and other groups seeking to protect the people's right to vote, as well as political campaigns which have a vested interest in maintaining fair and free elections.
